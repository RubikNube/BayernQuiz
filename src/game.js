export function questionTopic(game, target = currentQuestion(game)) {
  return game?.mode === "mix" || game?.mode === "correction" ? target?.topic : game?.mode;
}

function questionKey(game, target) {
  return game.mode === "mix" || game.mode === "correction" ? target.key : target.code;
}

export function resolveQuestion(topic, code) {
  const items = topic === "seat" ? REGIONS : MAP_TOPICS[topic];
  return Array.isArray(items) ? items.find(item => item.code === code) ?? null : null;
}

export function createCorrectionGame(references, random = Math.random) {
  if (!Array.isArray(references) || !references.length || references.length > 10) throw new Error("Expected 1 to 10 saved questions");
  const seen = new Set();
  const questions = references.map(({ topic, code }) => {
    const target = resolveQuestion(topic, code);
    const key = `${topic}:${code}`;
    if (!target || seen.has(key)) throw new Error("Invalid or duplicate saved question");
    seen.add(key);
    return { ...target, topic, key };
  });
  return newRound("correction", shuffle(questions, random), true);
}

function createMixedQuestions(count, random) {
  const topics = shuffle(Object.keys(MAP_TOPICS), random);
  const questions = topics.flatMap((topic, index) => {
    const size = Math.floor(count / topics.length) + (index < count % topics.length ? 1 : 0);
    return shuffle(MAP_TOPICS[topic], random).slice(0, size)
      .map(item => ({ ...item, topic, key: `${topic}:${item.code}` }));
  });
  return shuffle(questions, random);
}

export function getAllowedQuestionCounts(mode) {
  if (mode === "mix") return [7, 10, 15, 20];
  if (!["map", "seat", "river", "mountain", "sight", "city", "nature", "lake"].includes(mode)) return [];
  return mode === "city" ? [3, 5, 7, 10, 15, 20, 25] : mode === "river" ? [3, 5, 7, 10, 15, 20, 25, 30]
    : (mode === "sight" || mode === "nature" || mode === "lake") ? [3, 5, 7, 10, 15, 20] : mode === "mountain" ? [3, 5, 7, 10, 15] : [3, 5, 7];
}

export function createGame(mode, count, random = Math.random) {
  const allowedCounts = getAllowedQuestionCounts(mode);
  if (!allowedCounts.length) throw new Error("Unknown mode");
  if (!allowedCounts.includes(count)) {
    throw new Error("Invalid question count");
  }
  return newRound(mode, mode === "mix" ? createMixedQuestions(count, random)
    : shuffle(mode === "seat" ? REGIONS : MAP_TOPICS[mode], random).slice(0, count));
}

function newRound(mode, questions, isPractice = false) {
  return {
    mode,
    questions,
    isPractice,
    history: [],
    index: 0,
    score: 0,
    answered: false,
    selectedCode: null,
    options: [],
    finished: false,
  };
}

export function createRetryGame(completedGame, random = Math.random) {
  if (!completedGame?.finished) throw new Error("A finished round is required");
  const missed = new Set(completedGame.history.filter(({ correct }) => !correct).map(({ questionKey, questionCode }) => questionKey ?? questionCode));
  const questions = completedGame.questions.filter(target => missed.has(questionKey(completedGame, target)));
  if (!questions.length) throw new Error("No mistakes to retry");
  return newRound(completedGame.mode, shuffle(questions, random), true);
}

export function questionText(mode, target) {
  if (mode === "nature") return `Wo liegt das Naturschutzgebiet »${target.name}«?`;
  if (mode === "sight" || mode === "mountain") return `Finde ${target.name} auf der Karte.`;
  if (mode === "river") return `Wo fließt ${target.name}?`;
  if (mode === "seat") return `Wo ist der Sitz der Regierung von ${target.name}?`;
  return `Wo liegt ${target.name}?`;
}

export function getMistakeReview(game) {
  if (!game?.finished) return [];
  return game.history.filter(({ correct }) => !correct).map(({ questionCode, questionKey: key, selectedCode }) => {
    const target = game.questions.find(item => questionKey(game, item) === (key ?? questionCode));
    const topic = questionTopic(game, target);
    const items = topic === "seat" ? [...REGIONS, ...OTHER_CITIES] : MAP_TOPICS[topic];
    const selected = items.find(({ code }) => code === selectedCode);
    return {
      question: questionText(topic, target),
      selectedAnswer: topic === "seat" ? selected.seat : selected.name,
      correctAnswer: topic === "seat" ? target.seat : target.name,
    };
  });
}

export function currentQuestion(game) {
  return game.questions[game.index] ?? null;
}

export function makeSeatOptions(game, random = Math.random) {
  const target = currentQuestion(game);
  if (!target || questionTopic(game, target) !== "seat") return [];
  const otherSeat = shuffle(REGIONS.filter((region) => region.code !== target.code), random)[0];
  const localCity = shuffle(OTHER_CITIES.filter((city) => city.regionCode === target.code), random)[0];
  const otherCity = shuffle(OTHER_CITIES.filter((city) => city.regionCode !== target.code), random)[0];
  game.options = shuffle([target, otherSeat, localCity, otherCity], random);
  return game.options;
}

export function answer(game, selectedCode) {
  if (game.finished || game.answered) return null;
  const target = currentQuestion(game);
  if (!target) return null;
  const topic = questionTopic(game, target);
  const valid = topic === "seat"
    ? game.options.some((option) => option.code === selectedCode)
    : MAP_TOPICS[topic].some((item) => item.code === selectedCode);
  if (!valid) return null;
  const correct = target.code === selectedCode;
  game.answered = true;
  game.selectedCode = selectedCode;
  game.history.push({ questionCode: target.code, selectedCode, correct,
    ...(game.mode === "mix" || game.mode === "correction" ? { topic, questionKey: target.key } : {}),
  });
  if (correct) game.score += 1;
  return correct;
}

export function nextQuestion(game) {
  if (!game.answered || game.finished) return false;
  game.index += 1;
  game.answered = false;
  game.selectedCode = null;
  game.options = [];
  game.finished = game.index >= game.questions.length;
  return true;
}
